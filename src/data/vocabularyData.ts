// Helper to shuffle an array
export function shuffleArray<T>(array: T[]): T[] {
  const cloned = [...array];
  for (let i = cloned.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [cloned[i], cloned[j]] = [cloned[j], cloned[i]];
  }
  return cloned;
}

// Generate 20 randomized questions for a selected level
export function generateQuizQuestions(level: VocabularyLevel, count: number = 20): VocabularyWord[] {
  // Filter all words matching the level
  const levelPool = RAW_VOCABULARY_DATABASE.filter((item) => item.level === level);
  const shuffledPool = shuffleArray(levelPool);
  const selectedWords = shuffledPool.slice(0, Math.min(count, shuffledPool.length));

  // If pool has fewer than 20 (though we put 25), fill from adjacent levels
  if (selectedWords.length < count) {
    const backupPool = RAW_VOCABULARY_DATABASE.filter((item) => item.level !== level);
    const extra = shuffleArray(backupPool).slice(0, count - selectedWords.length);
    selectedWords.push(...extra);
  }

  // All words in level for generating distractors
  const allWordNames = RAW_VOCABULARY_DATABASE.map((item) => item.word);

  return selectedWords.map((item) => {
    // Pick 3 distractors from same level if possible, else any
    const sameLevelDistractors = RAW_VOCABULARY_DATABASE.filter(
      (w) => w.level === item.level && w.word !== item.word
    ).map((w) => w.word);

    const otherDistractors = allWordNames.filter(
      (w) => w !== item.word && !sameLevelDistractors.includes(w)
    );

    const candidateDistractors = shuffleArray(
      sameLevelDistractors.length >= 3 ? sameLevelDistractors : [...sameLevelDistractors, ...otherDistractors]
    ).slice(0, 3);

    const options = shuffleArray([item.word, ...candidateDistractors]);

    return {
      ...item,
      options,
      correctWord: item.word,
    };
  });
}
